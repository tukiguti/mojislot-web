# 文字 → RGBA。'.' は透過。
#
# **ランプ（暗→明の段）を素材ごとに作り、色相をずらす。** 明度だけ下げると色が濁る
# ので、暗い側は青〜赤へ、明るい側は黄へ寄せる。肌の影は赤味を足すと血色が残る。
# 光源は**左上ひとつ**に固定（外周を一律に暗くする「ピロー塗り」はしない）。
